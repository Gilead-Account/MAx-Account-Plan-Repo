import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
test('hierarchy and issues persist with CRM parent IDs across reloads', async () => {
 const previousWindow = globalThis.window;
 const storage = new Map();
 globalThis.window = { location: { search: '', hostname: 'localhost' }, localStorage: { getItem: (k) => storage.get(k) ?? null, setItem: (k,v) => storage.set(k,String(v)) } };
 const server = await createServer({ server: { middlewareMode: true, hmr: false, watch: null }, appType: 'custom' });
 try {
  const service = await server.ssrLoadModule('/src/lib/dataservice/accountPlan/payerHierarchy.js');
  const issues = await server.ssrLoadModule('/src/lib/dataservice/accountPlan/payerBarriersOpportunities.js');
  const query = await server.ssrLoadModule('/src/lib/dataservice/query.js');
  const draft = [{ id: 'draft-o', objective: 'Improve access', status: 'Open', strategies: [{ id: 'draft-s', strategy: 'Engage payer', status: 'Open', tactics: [{ id: 'draft-t', value: 'Meeting', status: 'Open' }] }] }];
  const saved = await service.savePayerHierarchy([], draft);
  const objective = saved.hierarchy[0];
  assert.notEqual(objective.id, 'draft-o');
  assert.equal(objective.strategies[0].id, saved.ids['draft-s']);
  assert.equal(objective.strategies[0].tactics[0].id, saved.ids['draft-t']);
  assert.deepEqual((await service.loadPayerHierarchy()).hierarchy, saved.hierarchy);
  const second = await service.savePayerHierarchy(saved.hierarchy, [...saved.hierarchy, { id: 'draft-o2', objective: 'Second objective', status: 'Open', strategies: [] }]);
  assert.equal(second.hierarchy.length, 2);
  assert.equal(second.hierarchy[1].textField, 'KPH_Objective_2__c');
  await issues.savePayerBarrierOpportunity({ type: 'Barrier', objectiveId: objective.id, strategyId: objective.strategies[0].id, name: 'Barrier', impact: 'High', status: 'Open', details: 'Details' });
  const barrier = (await issues.loadPayerBarriersOpportunities()).records[0];
  assert.equal(barrier.objectiveId, objective.id);
  assert.equal(barrier.strategyId, objective.strategies[0].id);
  const { activeRecordCount } = await server.ssrLoadModule('/src/lib/helper/barrierRecords.js');
  for (let index = 1; index < 5; index++) await issues.savePayerBarrierOpportunity({ ...barrier, id: undefined, name: `Barrier ${index}` });
  let reloaded = (await issues.loadPayerBarriersOpportunities()).records;
  assert.equal(reloaded.length, 5);
  assert.equal(activeRecordCount(reloaded, 'Barrier'), 5);
  await issues.savePayerBarrierOpportunity({ ...barrier, status: 'Completed' });
  reloaded = (await issues.loadPayerBarriersOpportunities()).records;
  assert.equal(reloaded.length, 5);
  assert.equal(activeRecordCount(reloaded, 'Barrier'), 4);
  await issues.savePayerBarrierOpportunity({ ...barrier, id: undefined, name: 'Replacement' });
  reloaded = (await issues.loadPayerBarriersOpportunities()).records;
  assert.equal(reloaded.length, 6);
  assert.equal(activeRecordCount(reloaded, 'Barrier'), 5);
  for (const row of reloaded) if (row.id !== barrier.id) await issues.deletePayerBarrierOpportunity(row.id);
  await issues.deletePayerBarrierOpportunity(barrier.id);
  assert.equal((await issues.loadPayerBarriersOpportunities()).records.length, 0);
  const beforeDelete = (await service.loadPayerHierarchy()).hierarchy;
  const withoutTactic = structuredClone(beforeDelete);
  withoutTactic[0].strategies[0].tactics = [];
  const tacticDeleted = await service.savePayerHierarchy(beforeDelete, withoutTactic);
  assert.equal((await service.loadPayerHierarchy()).hierarchy[0].strategies[0].tactics.length, 0);
  const tacticRows = (await query.runQuery({ object: 'KPH_Tactics_Resource__c', fields: ['Id', 'KPH_Is_Deleted__c', 'KPH_Tactics_and_Resources_Title__c'] })).map(query.unwrap);
  assert.equal(tacticRows[0].KPH_Is_Deleted__c, true);
  assert.equal(tacticRows[0].KPH_Tactics_and_Resources_Title__c, 'Meeting');
  const removed = await service.savePayerHierarchy(tacticDeleted.hierarchy, [second.hierarchy[1]]);
  assert.equal(removed.hierarchy.length, 1);
  assert.equal(removed.hierarchy[0].objective, 'Second objective');
  const objectiveRows = (await query.runQuery({ object: 'KPH_Account_Objective__c', fields: ['Id', 'KPH_Is_Deleted__c', 'KPH_Objective_1__c', 'KPH_Status__c'] })).map(query.unwrap);
  const deletedObjective = objectiveRows.find((row) => row.Id === objective.id);
  assert.equal(deletedObjective.KPH_Is_Deleted__c, true);
  assert.equal(deletedObjective.KPH_Objective_1__c, 'Improve access');
  assert.equal(deletedObjective.KPH_Status__c, 'Open');
  assert.deepEqual((await service.loadPayerHierarchy()).hierarchy, removed.hierarchy);
  const strategyRows = await query.runQuery({ object: 'KPH_Strategy__c', fields: ['Id', 'KPH_Is_Deleted__c'] });
  assert.equal(query.unwrap(strategyRows[0]).KPH_Is_Deleted__c, true);
  await assert.rejects(service.savePayerHierarchy([{ ...objective, id: 'other-plan' }], [{ ...objective, id: 'other-plan', objective: 'Wrong plan' }]), /no longer available/);
 } finally { await server.close(); globalThis.window = previousWindow; }
});
